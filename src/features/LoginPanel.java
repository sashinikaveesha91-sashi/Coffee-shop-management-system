    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed



        String inputUsername = username.getText();
        String inputPassword = new String(txtPassword.getPassword());


        if (inputUsername.isEmpty() || inputPassword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username and password cannot be empty!", "Error", JOptionPane.ERROR_MESSAGE);
            return; // Stop login validation.
        }



        String sql = "SELECT user_id, name, password, role FROM users WHERE username = ?";
        

        try (Connection conn = DatabaseConnection.getConnection(); 
             PreparedStatement stmt = conn.prepareStatement(sql)) {


            stmt.setString(1, inputUsername);

            // Execute the query.
            try (ResultSet rs = stmt.executeQuery()) {
                
                // Check the query result.
                if (rs.next()) {
                    // Username found.
                    String passwordFromDb = rs.getString("password");
                    String role = rs.getString("role");

                    // Compare the entered password with the stored password.


                    if (inputPassword.equals(passwordFromDb)) {

                        

                        int userId = rs.getInt("user_id");
                        String name = rs.getString("name");
                        
                        JOptionPane.showMessageDialog(this, "Login successful! Welcome, " + name);


                        if (role.equals("Owner")) {

                            logger.info("Opening Owner Dashboard...");

                            // This project uses the shared employee dashboard for the Owner role.
                            EmployeeDashboard ownerDashboard = new EmployeeDashboard(userId, name);
                            ownerDashboard.setVisible(true);
                            
                        } else {

                            

                            logger.info("Opening Employee Dashboard...");


                            // Open the employee dashboard using the current user ID and name.
                            EmployeeDashboard employeeDashboard = new EmployeeDashboard(userId, name);
                            employeeDashboard.setVisible(true);
                        }
                        

                        this.dispose(); 

                    } else {
                        // Incorrect password.
                        JOptionPane.showMessageDialog(this, "Incorrect password!", "Error", JOptionPane.ERROR_MESSAGE);
                    }

                } else {

                    JOptionPane.showMessageDialog(this, "Username not found!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (SQLException e) {

            logger.severe("Database Error: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "A database error occurred. Please contact the administrator.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_loginActionPerformed

