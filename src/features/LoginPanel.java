    private void forgotPasswordMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_forgotPasswordMouseClicked
        // 1. Show the confirmation dialog
        int response = JOptionPane.showConfirmDialog(this, 
                "Did you forget your password and want to continue?", 
                "Forgot Password Confirmation", 
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);
        

        if (response == JOptionPane.YES_OPTION) {

            


            logger.info("Opening the Forgot Password panel...");
            ForgotPasswordPanel forgotFrame = new ForgotPasswordPanel();
            forgotFrame.setVisible(true);
            

            this.dispose();
            
        } else {

            // No perlu melakukan apa-apa
            logger.info("Forgot password action cancelled.");
        }
    }//GEN-LAST:event_forgotPasswordMouseClicked

